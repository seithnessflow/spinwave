#!/usr/bin/env python3
"""Writes the golden corpus: one case per thing worth pinning down.

Cases are small and mechanical, so they are generated rather than typed:
a table here beats forty near-identical files drifting apart by hand. Run
this whenever the corpus grows, then regenerate the references:

    python tools/golden/make_cases.py
    for c in tools/golden/cases/*.txt; do
        tools/golden/build/vital_golden "$c" \
            "tools/golden/reference/$(basename "${c%.txt}").raw"
    done

Two rules every case obeys, both learned the hard way:

* `random_phase 0` is mandatory. It defaults to 1, and two engines cannot
  agree sample for sample on a waveform that starts somewhere random.

* The first note is a primer that `skip` excludes. The reference scoops
  its very first note up from MIDI note 0 (its last-played-note starts at
  zero), which Spinwave deliberately does not reproduce; see the note in
  spinwave-engine/src/allocator.rs. Skipping the glide alone is not
  enough, because it leaves the two oscillators a fixed phase apart, so
  the primer has to be a whole note the next one resets the phase from.
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
CASES = os.path.join(HERE, "cases")

PREAMBLE = """\
# {title}
#
# Generated by tools/golden/make_cases.py; edit that, not this.
rate 44100
seconds 2.0
skip 1.0
wave {wave}
set osc_1_on 1
set osc_1_level 0.7
set osc_1_random_phase 0
set osc_1_phase 0
"""

FOOTER = """\
note 45 0.9 0.0 0.3
note {note} 0.9 1.1 0.6
"""


def case(name, title, settings, wave="saw", note=45, modulations=(), extra_notes=()):
    """One case: a preamble, the settings under test, the two notes.

    `extra_notes` adds `(midi, velocity, start, hold)` events on top, for
    the cases that need more than one voice sounding at a time.
    """
    body = PREAMBLE.format(title=title, wave=wave)
    for key, value in settings:
        body += "set {} {}\n".format(key, value)
    for source, destination, amount in modulations:
        body += "modulate {} {} {}\n".format(source, destination, amount)
    body += FOOTER.format(note=note)
    for midi, velocity, start, hold in extra_notes:
        body += "note {} {} {} {}\n".format(midi, velocity, start, hold)
    with open(os.path.join(CASES, name + ".txt"), "w", newline="\n") as out:
        out.write(body)


# -- The corpus --------------------------------------------------------------

# The plain path first: if this diverges, nothing below means anything.
case("osc_saw_dry", "A bare saw: no filter, no effects, no modulation",
     [("filter_1_on", 0)])

# Every waveform the reference ships, through the same bare path. These
# pin the oscillator's band-limiting and its wavetable reading.
for wave in ("sin", "triangle", "square", "pulse"):
    case("osc_wave_" + wave, "A bare {} through the plain path".format(wave),
         [("filter_1_on", 0)], wave=wave)

# Phase distortion: the shapes that make Vital sound like Vital. Amount is
# held at 0.6 so each mode is doing real work rather than sitting near its
# neutral point.
PHASE_MODES = [
    (1, "sync"), (2, "formant"), (3, "quantize"), (4, "bend"),
    (5, "squeeze"), (6, "pulse_width"), (7, "fm_from_a"), (8, "fm_from_b"),
    (9, "rm_from_a"), (10, "rm_from_b"), (11, "phase_disperse"), (12, "fm_a_b"),
]
for index, name in PHASE_MODES:
    case("osc_warp_" + name,
         "Phase distortion mode {} ({})".format(index, name),
         [("filter_1_on", 0),
          ("osc_1_distortion_type", index),
          ("osc_1_distortion_amount", 0.6)])

# Spectral morphs, same idea: each mode at a working amount.
MORPH_MODES = [
    (1, "vocode"), (2, "formant_scale"), (3, "harmonic_stretch"),
    (4, "inharmonic_stretch"), (5, "smear"), (6, "random_amplitudes"),
    (7, "low_pass"), (8, "high_pass"), (9, "phase_disperse"),
    (10, "shepard"), (11, "spectral_time_skew"),
]
for index, name in MORPH_MODES:
    case("osc_morph_" + name,
         "Spectral morph mode {} ({})".format(index, name),
         [("filter_1_on", 0),
          ("osc_1_spectral_morph_type", index),
          ("osc_1_spectral_morph_amount", 0.6)])

# Unison: the detune law, the stereo spread and the voice stacking.
case("osc_unison", "Seven-voice unison, wide detune",
     [("filter_1_on", 0),
      ("osc_1_unison_voices", 7),
      ("osc_1_unison_detune", 6.0),
      ("osc_1_unison_blend", 0.7),
      ("osc_1_stereo_spread", 0.8)])

# Filters: every model, twice. Low resonance shows the response, high
# resonance shows the saturator and the feedback path.
FILTER_MODELS = [
    (0, "analog"), (1, "dirty"), (2, "ladder"), (3, "digital"),
    (4, "diode"), (5, "formant"), (6, "comb"), (7, "phaser"),
]
for index, name in FILTER_MODELS:
    for resonance, label in ((0.3, "low_q"), (0.85, "high_q")):
        case("filter_{}_{}".format(name, label),
             "Filter model {} ({}) at resonance {}".format(index, name, resonance),
             [("filter_1_on", 1),
              ("filter_1_model", index),
              ("filter_1_cutoff", 72.0),
              ("filter_1_resonance", resonance),
              ("filter_1_drive", 6.0)])

# Effects, one at a time, each with its dry/wet up so the effect is what
# the comparison is looking at.
EFFECTS = [
    ("chorus", [("chorus_dry_wet", 0.8)]),
    ("delay", [("delay_dry_wet", 0.8), ("delay_feedback", 0.5)]),
    ("distortion", [("distortion_drive", 12.0), ("distortion_mix", 1.0)]),
    ("eq", [("eq_low_gain", 8.0), ("eq_high_gain", -8.0)]),
    ("flanger", [("flanger_dry_wet", 0.8), ("flanger_feedback", 0.6)]),
    ("phaser", [("phaser_dry_wet", 0.8), ("phaser_feedback", 0.6)]),
    ("reverb", [("reverb_dry_wet", 0.8), ("reverb_decay_time", 1.0)]),
    ("compressor", [("compressor_mix", 1.0)]),
    ("filter_fx", [("filter_fx_cutoff", 70.0), ("filter_fx_resonance", 0.6)]),
]
for name, settings in EFFECTS:
    case("fx_" + name, "The {} effect on its own".format(name),
         [("filter_1_on", 0), (name + "_on", 1)] + settings)

# Envelope shapes: the quartic time scaling and the sustain law.
case("env_fast", "A short percussive envelope",
     [("filter_1_on", 0),
      ("env_1_attack", 0.0), ("env_1_decay", 0.35),
      ("env_1_sustain", 0.0), ("env_1_release", 0.2)])
case("env_slow", "A slow pad envelope",
     [("filter_1_on", 0),
      ("env_1_attack", 0.5), ("env_1_decay", 0.7),
      ("env_1_sustain", 0.8), ("env_1_release", 0.6)])

# The modulation matrix, which is where this week's worst bug lived: the
# LFO and random sources were squashed into the top half of their range,
# halving every modulation depth, and no test noticed. A connection is not
# a control on either side, so both harnesses wire these through their own
# path and the `modulate` directive drives both.

# An LFO on the filter cutoff: the plainest control-rate path.
case("mod_lfo_to_cutoff", "LFO 1 to filter cutoff, the plain control-rate path",
     [("filter_1_on", 1), ("filter_1_model", 3),
      ("filter_1_cutoff", 60.0), ("filter_1_resonance", 0.4),
      ("lfo_1_frequency", 2.0)],
     modulations=[("lfo_1", "filter_1_cutoff", 0.7)])

# Bipolar, which takes the other branch of the transform.
case("mod_lfo_bipolar", "The same LFO, bipolar",
     [("filter_1_on", 1), ("filter_1_model", 3),
      ("filter_1_cutoff", 80.0), ("filter_1_resonance", 0.4),
      ("lfo_1_frequency", 2.0),
      ("modulation_1_bipolar", 1)],
     modulations=[("lfo_1", "filter_1_cutoff", 0.7)])

# The bipolar case passes and the unipolar one fails, on the same source
# and the same destination. Two things differ, not one: the polarity AND
# the base cutoff (80 against 60). These two split them. If the unipolar
# case passes at 80 the polarity is innocent and the base value decides
# how much a cutoff error is worth; if it still fails, polarity is real.
case("mod_lfo_to_cutoff_high", "The unipolar LFO at the bipolar case's base cutoff",
     [("filter_1_on", 1), ("filter_1_model", 3),
      ("filter_1_cutoff", 80.0), ("filter_1_resonance", 0.4),
      ("lfo_1_frequency", 2.0)],
     modulations=[("lfo_1", "filter_1_cutoff", 0.7)])

case("mod_lfo_bipolar_low", "The bipolar LFO at the unipolar case's base cutoff",
     [("filter_1_on", 1), ("filter_1_model", 3),
      ("filter_1_cutoff", 60.0), ("filter_1_resonance", 0.4),
      ("lfo_1_frequency", 2.0),
      ("modulation_1_bipolar", 1)],
     modulations=[("lfo_1", "filter_1_cutoff", 0.7)])

# The same unipolar LFO into a destination the kernel does NOT consume
# per sample. Filter cutoff is the one audio-rate destination, so
# lfo -> cutoff is evaluated sample by sample while lfo -> level is
# evaluated once per block. If this passes, the fault is confined to the
# audio-rate path; if it fails too, it is the transform or the source and
# the path is innocent.
case("mod_lfo_to_level", "The unipolar LFO into a control-rate destination",
     [("filter_1_on", 0)],
     modulations=[("lfo_1", "osc_1_level", 0.7)])

# An envelope on pitch: a per-voice destination rather than the filter.
case("mod_env_to_pitch", "Envelope 2 to oscillator pitch",
     [("filter_1_on", 0),
      ("env_2_attack", 0.0), ("env_2_decay", 0.4),
      ("env_2_sustain", 0.3), ("env_2_release", 0.3)],
     modulations=[("env_2", "osc_1_transpose", 0.5)])

# An envelope on level: the amplitude path, where the squashing bug bit.
case("mod_env_to_level", "Envelope 2 to oscillator level",
     [("filter_1_on", 0),
      ("env_2_attack", 0.1), ("env_2_decay", 0.5),
      ("env_2_sustain", 0.4), ("env_2_release", 0.3)],
     modulations=[("env_2", "osc_1_level", 0.8)])

# Two sources stacked on one destination: the matrix has to sum them.
case("mod_two_sources_one_dest", "An LFO and an envelope on the same cutoff",
     [("filter_1_on", 1), ("filter_1_model", 3),
      ("filter_1_cutoff", 55.0), ("filter_1_resonance", 0.4),
      ("lfo_1_frequency", 3.0),
      ("env_2_attack", 0.0), ("env_2_decay", 0.5), ("env_2_sustain", 0.2)],
     modulations=[("lfo_1", "filter_1_cutoff", 0.4),
                  ("env_2", "filter_1_cutoff", 0.5)])

# A source that does not move. Every other modulation case changes at the
# note onset from both ends at once: the source starts (an envelope from
# zero, an LFO from its retrigger phase, a random value drawn fresh) and
# the destination begins receiving modulation. That confounds the two, and
# it is why the divergence in those cases could not be pinned on either.
# A macro sits at a fixed value from before the first note until after the
# last, so an onset ramp seen HERE belongs to the destination path and
# nothing else; the absence of one puts the blame on the sources.
case("mod_macro_to_cutoff", "Macro 1, a source that never moves, to filter cutoff",
     [("filter_1_on", 1), ("filter_1_model", 3),
      ("filter_1_cutoff", 55.0), ("filter_1_resonance", 0.4),
      ("macro_control_1", 0.75)],
     modulations=[("macro_control_1", "filter_1_cutoff", 0.7)])

# A source that is POLY but does not move, which is the case that splits
# the two things `mod_macro_to_cutoff` proves at once. A macro differs
# from the failing cases twice over: it is mono rather than poly, AND
# constant rather than varying. Velocity is per-voice like an LFO and
# fixed for the life of the note like a macro, so it isolates the route
# from the dynamics. If this FAILS the poly route is at fault whatever the
# source does; if it PASSES the fault is in what varies over time, and the
# one-block lead the probe found becomes the suspect again.
case("mod_velocity_to_cutoff", "Velocity: a poly source that never moves, to cutoff",
     [("filter_1_on", 1), ("filter_1_model", 3),
      ("filter_1_cutoff", 55.0), ("filter_1_resonance", 0.4)],
     modulations=[("velocity", "filter_1_cutoff", 0.7)])

# The same question asked of key tracking, which is poly, constant, and
# reaches the voice by a different route than velocity does.
case("mod_note_to_cutoff", "Note (key tracking), the other poly constant, to cutoff",
     [("filter_1_on", 1), ("filter_1_model", 3),
      ("filter_1_cutoff", 55.0), ("filter_1_resonance", 0.4)],
     modulations=[("note", "filter_1_cutoff", 0.7)])

# Two notes at once, so the second occupies the OTHER lane of the voice
# pair. A fold across voice lanes that is counted twice or dropped shows
# up here and not on a single note, because with one voice the wrong fold
# and the right one agree.
case("mod_two_voices_one_lfo", "An LFO to cutoff with two voices sounding together",
     [("filter_1_on", 1), ("filter_1_model", 3),
      ("filter_1_cutoff", 55.0), ("filter_1_resonance", 0.4),
      ("lfo_1_frequency", 2.0)],
     modulations=[("lfo_1", "filter_1_cutoff", 0.7)],
     extra_notes=[(52, 0.8, 1.15, 0.5)])

# The random source, whose value is drawn per note.
case("mod_random_to_cutoff", "Random 1 to filter cutoff",
     [("filter_1_on", 1), ("filter_1_model", 3),
      ("filter_1_cutoff", 65.0), ("filter_1_resonance", 0.4),
      ("random_1_frequency", 1.0)],
     modulations=[("random_1", "filter_1_cutoff", 0.6)])


# Pitch: a note two octaves up exercises the band-limiting hardest, where
# a mip-selection difference would show.
case("osc_high_note", "The same saw two octaves up, hardest on band-limiting",
     [("filter_1_on", 0)], note=69)

print("wrote {} cases to {}".format(len(os.listdir(CASES)), CASES))
