#!/usr/bin/env python3
"""Writes the golden corpus: one case per thing worth pinning down.

Cases are small and mechanical, so they are generated rather than typed:
a table here beats forty near-identical files drifting apart by hand. Run
this whenever the corpus grows, then regenerate the references:

    python tools/golden/make_cases.py
    for c in tools/golden/cases/*.txt; do
        tools/golden/build/vital_golden "$c" \
            "tools/golden/reference/$(basename "${c%.txt}").raw"
    done

Two rules every case obeys, both learned the hard way:

* `random_phase 0` is mandatory. It defaults to 1, and two engines cannot
  agree sample for sample on a waveform that starts somewhere random.

* The first note is a primer that `skip` excludes. The reference scoops
  its very first note up from MIDI note 0 (its last-played-note starts at
  zero), which Spinwave deliberately does not reproduce; see the note in
  spinwave-engine/src/allocator.rs. Skipping the glide alone is not
  enough, because it leaves the two oscillators a fixed phase apart, so
  the primer has to be a whole note the next one resets the phase from.
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
CASES = os.path.join(HERE, "cases")

PREAMBLE = """\
# {title}
#
# Generated by tools/golden/make_cases.py; edit that, not this.
rate 44100
seconds {seconds}
skip {skip}
wave {wave}
set osc_1_on 1
set osc_1_level 0.7
set osc_1_random_phase 0
set osc_1_phase 0
"""

FOOTER = """\
note 45 0.9 0.0 0.3
note {note} 0.9 {start} 0.6
"""

# The primer note differs between the two engines by construction (the
# reference glides it from MIDI 0), and `skip` hides it — but not its
# ECHO: a delay of 250 ms with feedback 0.5 brings the primer back into
# the compared window at 0.5^4, and a reverb's tail lasts seconds.
# fx_delay's 1.4e-2 and fx_reverb's 6.4e-3 were the primer's echo, not
# the effect. A case with a delay line or a reverb skips 5 s instead of
# 1 (0.5^20 = 1e-6 for the delay; a 1 s decay is -240 dB by then).
LONG_SKIP = 5.0


def case(name, title, settings, wave="saw", note=45, modulations=(), extra_notes=(),
         random_seed=None, skip=1.0):
    """One case: a preamble, the settings under test, the two notes.

    `extra_notes` adds `(midi, velocity, start, hold)` events on top, for
    the cases that need more than one voice sounding at a time.
    `random_seed` pins the Spinwave side's random LFO seed to the one the
    reference's construction order gives it (see random_seed.py).
    """
    body = PREAMBLE.format(title=title, wave=wave, seconds=skip + 1.0, skip=skip)
    for key, value in settings:
        body += "set {} {}\n".format(key, value)
    for slot, modulation in enumerate(modulations, start=1):
        source, destination, amount = modulation[:3]
        flags = modulation[3] if len(modulation) > 3 else {}
        body += "modulate {} {} {}\n".format(source, destination, amount)
        # Every connection states its polarity. The reference creates a
        # NEW connection bipolar when the source is an lfo / random /
        # stereo / pitch (kBipolarModulationSourcePrefixes), a fact that
        # cost a whole session while the harness relied on defaults; a
        # case that means unipolar says so, on every slot.
        body += "set modulation_{}_bipolar {}\n".format(slot, flags.get("bipolar", 0))
        for key in ("power", "stereo", "bypass"):
            if key in flags:
                body += "set modulation_{}_{} {}\n".format(slot, key, flags[key])
    if random_seed is not None:
        body += "random_seed {}\n".format(random_seed)
    body += FOOTER.format(note=note, start=skip + 0.1)
    for midi, velocity, start, hold in extra_notes:
        body += "note {} {} {} {}\n".format(midi, velocity, start + skip - 1.0, hold)
    with open(os.path.join(CASES, name + ".txt"), "w", newline="\n") as out:
        out.write(body)


