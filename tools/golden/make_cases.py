# -- The remaining mono destinations of the real bank (2026-09-13) ---------
#
# Every control the reference creates with createMonoModControl and the
# 75 presets modulate. Each gets a macro (a constant) with a static twin
# set to the value the macro should produce: identical references say
# the route and the scale are right without any reading of the code
# (the regime, per block on both sides, is the control-rate route that
# mod_lfo_to_distortion_mix already proves). Offsets add to the STORED
# value — before the square of a Quadratic control (eq resonances,
# reverb chorus amount) and before the exp2 of an Exponential one
# (chorus delays) — so the twin sets stored + macro × amount × range.
# Every value stays interior to its range (bounds.rs checks).
STEREO = [("osc_1_unison_voices", 4), ("osc_1_unison_detune", 2.0),
          ("osc_1_stereo_spread", 1.0)]
def mono_dest(destination, effect, settings, base, amount, range_, extra=()):
    macro = 0.5
    expected = base + macro * amount * range_
    common = [("filter_1_on", 0), (effect + "_on", 1), ("macro_control_1", macro)]
    common += list(extra)
    skip = LONG_SKIP if effect in ("delay", "reverb") else 1.0
    case("mono_macro_to_" + destination, "A macro into " + destination,
         common + settings + [(destination, base)],
         modulations=[("macro_control_1", destination, amount)], skip=skip)
    case("mono_macro_to_" + destination + "_static",
         "The value the macro should give " + destination + ", set statically",
         common + settings + [(destination, round(expected, 8))], skip=skip)

